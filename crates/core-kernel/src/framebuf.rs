/// Return a reference to the 8×8 glyph for `ch`.  Non-printable → solid block.
#[inline]
fn font_glyph(ch: u8) -> &'static [u8; 8] {
    let idx = if ch >= 0x20 && ch <= 0x7F { (ch - 0x20) as usize } else { 95 };
    &FONT8X8[idx]
}

// ── Panic screen renderer ─────────────────────────────────────────────────────

/// Convert ARGB `0x00_RR_GG_BB` to the native framebuffer word (Rgb32 or Bgr32).
#[inline]
fn to_native(argb: u32, format: u32) -> u32 {
    let r = (argb >> 16) & 0xFF;
    let g = (argb >>  8) & 0xFF;
    let b =  argb        & 0xFF;
    if format == FMT_BGR32 {
        (b << 16) | (g << 8) | r
    } else {
        (r << 16) | (g << 8) | b  // Rgb32 (default)
    }
}

/// Write one pixel at (x, y) directly to the mapped framebuffer.
///
/// # Safety
/// `fb_virt` must be a valid kernel VA for `stride * height * 4` bytes.
#[inline]
unsafe fn put_pixel_raw(fb_virt: u64, stride: u32, x: u32, y: u32, native: u32) {
    let off = (y as u64 * stride as u64 + x as u64) * 4;
    let ptr = (fb_virt + off) as *mut u32;
    core::ptr::write_volatile(ptr, native);
}

/// Fill a rectangle (pixel coords) with a single native color.
unsafe fn fill_rect(fb_virt: u64, stride: u32, x: u32, y: u32, w: u32, h: u32, native: u32) {
    for row in y..y + h {
        for col in x..x + w {
            put_pixel_raw(fb_virt, stride, col, row, native);
        }
    }
}

/// Draw one 8×8 glyph at character cell (cx, cy).
unsafe fn draw_glyph(
    fb_virt: u64, stride: u32, width: u32, height: u32,
    cx: u32, cy: u32, ch: u8, fg: u32, bg: u32,
) {
    let px = cx * 8;
    let py = cy * 8;
    if px + 8 > width || py + 8 > height { return; }
    let glyph = font_glyph(ch);
    for gy in 0..8u32 {
        let row_bits = glyph[gy as usize];
        for gx in 0..8u32 {
            let on = row_bits & (0x80 >> gx) != 0;
            put_pixel_raw(fb_virt, stride, px + gx, py + gy, if on { fg } else { bg });
        }
    }
}

/// Draw a byte string starting at character cell (cx, cy).
/// Returns the column after the last character written.
unsafe fn draw_str(
    fb_virt: u64, stride: u32, width: u32, height: u32,
    cx: u32, cy: u32, s: &[u8], fg: u32, bg: u32,
) -> u32 {
    let mut col = cx;
    for &b in s {
        draw_glyph(fb_virt, stride, width, height, col, cy, b, fg, bg);
        col += 1;
    }
    col
}

/// Draw a 64-bit value as 16 hex digits at character cell (cx, cy).
unsafe fn draw_hex64(
    fb_virt: u64, stride: u32, width: u32, height: u32,
    cx: u32, cy: u32, val: u64, fg: u32, bg: u32,
) {
    const HEX: &[u8] = b"0123456789ABCDEF";
    for i in 0..16u32 {
        let nibble = ((val >> (60 - i * 4)) & 0xF) as usize;
        draw_glyph(fb_virt, stride, width, height, cx + i, cy, HEX[nibble], fg, bg);
    }
}

/// Draw a 32-bit value as 8 hex digits.
unsafe fn draw_hex32(
    fb_virt: u64, stride: u32, width: u32, height: u32,
    cx: u32, cy: u32, val: u32, fg: u32, bg: u32,
) {
    const HEX: &[u8] = b"0123456789ABCDEF";
    for i in 0..8u32 {
        let nibble = ((val >> (28 - i * 4)) & 0xF) as usize;
        draw_glyph(fb_virt, stride, width, height, cx + i, cy, HEX[nibble], fg, bg);
    }
}

/// Draw a kernel panic screen directly to the GOP framebuffer.
///
/// Safe to call from any exception handler after `set_kernel_fb_virt()` has
/// been called (Stage 4).  If the framebuffer VA is not yet set, returns
/// immediately (UART output is the fallback).
///
/// # Parameters
/// - `label`: short description, e.g. `b"#PF  Page Fault"`
/// - `rip`:   faulting instruction pointer
/// - `err`:   exception error code (0 if none)
/// - `cr2`:   CR2 value (0 for non-#PF exceptions)
pub fn panic_screen(label: &[u8], rip: u64, err: u64, cr2: u64) {
    let fb_virt = KERN_FB_VIRT.load(Ordering::Acquire);
    if fb_virt == 0 { return; }

    let fb = match get_primary() {
        Some(f) => f,
        None    => return,
    };

    let format = fb.format;
    let stride = fb.stride;
    let width  = fb.width;
    let height = fb.height;

    // Colors
    let bg_native  = to_native(0x00_AA_00_00, format); // dark red
    let hdr_native = to_native(0x00_FF_00_00, format); // bright red header bar
    let fg_native  = to_native(0x00_FF_FF_FF, format); // white text
    let fg_yel     = to_native(0x00_FF_FF_00, format); // yellow label
    let fg_grn     = to_native(0x00_00_FF_00, format); // green field names

    unsafe {
        // 1. Fill entire screen dark red
        fill_rect(fb_virt, stride, 0, 0, width, height, bg_native);

        // 2. Bright red header bar (top 12 pixels = 1.5 char rows)
        fill_rect(fb_virt, stride, 0, 0, width, 12, hdr_native);

        // 3. Title line (row 0)
        draw_str(fb_virt, stride, width, height, 1, 0,
            b"*** KERNEL PANIC ***", fg_native, hdr_native);

        // 4. Exception label (row 2)
        draw_str(fb_virt, stride, width, height, 2, 2, label, fg_yel, bg_native);

        // 5. Register fields (rows 4–7)
        draw_str(fb_virt, stride, width, height, 2, 4, b"RIP=", fg_grn, bg_native);
        draw_hex64(fb_virt, stride, width, height, 6, 4, rip, fg_native, bg_native);

        draw_str(fb_virt, stride, width, height, 2, 5, b"ERR=", fg_grn, bg_native);
        draw_hex64(fb_virt, stride, width, height, 6, 5, err, fg_native, bg_native);

        draw_str(fb_virt, stride, width, height, 2, 6, b"CR2=", fg_grn, bg_native);
        draw_hex64(fb_virt, stride, width, height, 6, 6, cr2, fg_native, bg_native);

        // PID (row 8)
        let pid = core_kernel_pid();
        draw_str(fb_virt, stride, width, height, 2, 8, b"PID=", fg_grn, bg_native);
        draw_hex32(fb_virt, stride, width, height, 6, 8, pid, fg_native, bg_native);

        // 6. Footer: "System halted." (row 10)
        draw_str(fb_virt, stride, width, height, 2, 10,
            b"System halted. See serial console for details.", fg_native, bg_native);
    }
}

/// Fetch current PID without pulling in the whole scheduler module.
#[inline]
fn core_kernel_pid() -> u32 {
    crate::scheduler::CURRENT_PID.load(Ordering::Relaxed)
}
