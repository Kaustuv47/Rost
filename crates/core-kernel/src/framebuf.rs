//! Primary GOP framebuffer descriptor — shared between kernel and syscall layer.
//!
//! The kernel populates this once at Stage 0 (before scheduler starts) by
//! calling `set_primary()` after discovering the GOP framebuffer via UEFI boot
//! services.  The syscall handler reads it to serve `SYS_GET_FRAMEBUF (33)`.
//!
//! `set_kernel_fb_virt()` is called during Stage 4 after the framebuffer MMIO
//! pages have been identity-mapped into the kernel PML4.  After that call,
//! `panic_screen()` can draw directly to the display without the GOP server.

use core::sync::atomic::{AtomicU32, AtomicU64, Ordering};

// ── Stored descriptor (all zero = no framebuffer) ────────────────────────────

static FB_BASE:   AtomicU64 = AtomicU64::new(0);
static FB_SIZE:   AtomicU64 = AtomicU64::new(0);
static FB_WIDTH:  AtomicU32 = AtomicU32::new(0);
static FB_HEIGHT: AtomicU32 = AtomicU32::new(0);
static FB_STRIDE: AtomicU32 = AtomicU32::new(0);
/// Pixel format tag: 0 = Rgb32, 1 = Bgr32, 2 = Bitmask, 3 = BltOnly / unknown
static FB_FORMAT: AtomicU32 = AtomicU32::new(0);
/// Set to 1 once `set_primary` has been called.
static FB_VALID:  AtomicU32 = AtomicU32::new(0);

/// Virtual address of the mapped framebuffer (set in Stage 4, 0 = not yet mapped).
static KERN_FB_VIRT: AtomicU64 = AtomicU64::new(0);

/// Pixel format tag values (must match `FrameBufferFormat` discriminants sent to ring-3).
pub const FMT_RGB32:   u32 = 0;
pub const FMT_BGR32:   u32 = 1;
pub const FMT_BITMASK: u32 = 2;
pub const FMT_BLTONLY: u32 = 3;

// ── Public init ───────────────────────────────────────────────────────────────

/// Store the primary framebuffer descriptor.
///
/// Must be called by the kernel before ring-3 processes start (Stage 0 / Stage 1).
pub fn set_primary(base: u64, size: usize, width: u32, height: u32, stride: u32, format: u32) {
    FB_BASE  .store(base,          Ordering::Relaxed);
    FB_SIZE  .store(size as u64,   Ordering::Relaxed);
    FB_WIDTH .store(width,         Ordering::Relaxed);
    FB_HEIGHT.store(height,        Ordering::Relaxed);
    FB_STRIDE.store(stride,        Ordering::Relaxed);
    FB_FORMAT.store(format,        Ordering::Relaxed);
    FB_VALID .store(1,             Ordering::Release);
}

/// Record the virtual address at which the framebuffer MMIO has been mapped.
///
/// Called during Stage 4 after `map_page_global` has identity-mapped the
/// framebuffer pages.  On an identity-mapped kernel PML4, `virt == phys`.
pub fn set_kernel_fb_virt(virt: u64) {
    KERN_FB_VIRT.store(virt, Ordering::Release);
}

// ── Public read ───────────────────────────────────────────────────────────────

/// Framebuffer descriptor returned to callers.
#[derive(Copy, Clone)]
pub struct FbInfo {
    pub base:   u64,
    pub size:   u64,
    pub width:  u32,
    pub height: u32,
    pub stride: u32,
    pub format: u32,
}

/// Returns the primary framebuffer descriptor, or `None` if not populated.
pub fn get_primary() -> Option<FbInfo> {
    if FB_VALID.load(Ordering::Acquire) == 0 { return None; }
    Some(FbInfo {
        base:   FB_BASE  .load(Ordering::Relaxed),
        size:   FB_SIZE  .load(Ordering::Relaxed),
        width:  FB_WIDTH .load(Ordering::Relaxed),
        height: FB_HEIGHT.load(Ordering::Relaxed),
        stride: FB_STRIDE.load(Ordering::Relaxed),
        format: FB_FORMAT.load(Ordering::Relaxed),
    })
}

